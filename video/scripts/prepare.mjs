// Gets the video ready to preview or render, without touching design/ or
// plugin/: it copies the design system's stylesheet into src/generated as a
// string, minus its Google Fonts import (the video loads the repository's own
// font files instead), renders the soundtrack when its score changed, and lays
// KLWD's beat when its loops or where it plays changed. With --picture it
// stops before the sound, for the README's stills (scripts/readme.mjs).
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const video = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const root = resolve(video, '..')

const css = readFileSync(join(root, 'design/components/bundle.css'), 'utf8').replace(/@import url\([^)]*\);\s*/g, '')
const generated = join(video, 'src/generated')
mkdirSync(generated, { recursive: true })
const out = join(generated, 'design-css.ts')
const body = `// Generated by scripts/prepare.mjs from design/components/bundle.css. Do not edit.\nexport default ${JSON.stringify(css)}\n`
if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
  writeFileSync(out, body)
  console.log('src/generated/design-css.ts')
}

// The icon's layers, as markup to draw inline: as images their outer rings
// and towers would be cut at the canvas's edge, and they stay sharp at any
// size. layers.json says how they stack.
const iconDir = join(root, 'assets/icon-layers')
const layers = JSON.parse(readFileSync(join(iconDir, 'layers.json'), 'utf8'))
const markup = {}
for (const layer of [...layers.layers, layers.mask]) {
  markup[layer.name] = readFileSync(join(iconDir, layer.svg), 'utf8')
    .replace(/<\?xml[^>]*>\s*/, '')
    .replace(/<title>[^<]*<\/title>\s*/, '')
}
const iconOut = join(generated, 'icon-layers.ts')
const iconBody = `// Generated by scripts/prepare.mjs from assets/icon-layers. Do not edit.\nexport const LAYERS = ${JSON.stringify(layers, null, 2)} as const\n\nexport const MARKUP: Record<string, string> = ${JSON.stringify(markup, null, 2)}\n`
if (!existsSync(iconOut) || readFileSync(iconOut, 'utf8') !== iconBody) {
  writeFileSync(iconOut, iconBody)
  console.log('src/generated/icon-layers.ts')
}

// STORMTRACKER's four pictures of the earth, which its globe loads by name
// from a folder: served from public/textures
const textures = join(root, 'design/textures')
const texturesOut = join(video, 'public/textures')
mkdirSync(texturesOut, { recursive: true })
for (const name of readdirSync(textures).filter((file) => file.endsWith('.jpg'))) {
  const from = join(textures, name)
  const to = join(texturesOut, name)
  if (!existsSync(to) || statSync(to).size !== statSync(from).size) {
    copyFileSync(from, to)
    console.log(`public/textures/${name}`)
  }
}

// With --picture, only what the pictures need: the README's stills have no sound
if (process.argv.includes('--picture')) {
  process.exit(0)
}

// The soundtrack and its sound effects: rendered from their score only when
// the score, its renderer or the running order changed
const score = join(video, 'scripts/music/score.js')
if (existsSync(score)) {
  const hash = createHash('sha256')
    .update(readFileSync(score))
    .update(readFileSync(join(video, 'scripts/render-audio.mjs')))
    .update(readFileSync(join(video, 'src/timeline.ts')))
    .digest('hex')
  const stamp = join(video, 'public/audio/SOURCE')
  const stale = !existsSync(stamp) || readFileSync(stamp, 'utf8').trim() !== hash
  if (stale) {
    const { renderAudio } = await import('./render-audio.mjs')
    await renderAudio()
    mkdirSync(dirname(stamp), { recursive: true })
    writeFileSync(stamp, `${hash}\n`)
  }
}

// The promo's storm and score (scripts/music/storm.js through score.js's
// synth): only when either, the renderer or the promo's running order changed
const stormHash = createHash('sha256')
for (const file of ['scripts/music/score.js', 'scripts/music/storm.js', 'scripts/render-audio.mjs', 'src/promo/timeline.ts']) {
  stormHash.update(readFileSync(join(video, file)))
}
const stormSum = stormHash.digest('hex')
const stormStamp = join(video, 'public/audio/storm.SOURCE')
if (!existsSync(join(video, 'public/audio/storm.wav')) || !existsSync(stormStamp) || readFileSync(stormStamp, 'utf8').trim() !== stormSum) {
  const { renderStorm } = await import('./render-audio.mjs')
  await renderStorm()
  writeFileSync(stormStamp, `${stormSum}\n`)
}

// KLWD's beat, laid where the station plays it: only when the shipped loops,
// the contract's mix, how it is laid or the running order changed
const beatHash = createHash('sha256')
for (const file of [
  join(root, 'plugin/station/sounds/beat-minor.caf'),
  join(root, 'plugin/station/sounds/beat-major.caf'),
  join(root, 'packages/contract/src/constants.ts'),
  join(video, 'scripts/render-beat.mjs'),
  join(video, 'src/timeline.ts'),
]) {
  beatHash.update(readFileSync(file))
}
const beatSum = beatHash.digest('hex')
const beatStamp = join(video, 'public/audio/beat.SOURCE')
if (!existsSync(join(video, 'public/audio/beat.wav')) || !existsSync(beatStamp) || readFileSync(beatStamp, 'utf8').trim() !== beatSum) {
  const { renderBeat } = await import('./render-beat.mjs')
  renderBeat()
  writeFileSync(beatStamp, `${beatSum}\n`)
  console.log('public/audio/beat.wav')
}

// And the promo's, from its own running order
const promoBeatHash = createHash('sha256')
for (const file of [
  join(root, 'plugin/station/sounds/beat-minor.caf'),
  join(root, 'packages/contract/src/constants.ts'),
  join(video, 'scripts/render-beat.mjs'),
  join(video, 'src/promo/timeline.ts'),
]) {
  promoBeatHash.update(readFileSync(file))
}
const promoBeatSum = promoBeatHash.digest('hex')
const promoBeatStamp = join(video, 'public/audio/promo-beat.SOURCE')
if (!existsSync(join(video, 'public/audio/promo-beat.wav')) || !existsSync(promoBeatStamp) || readFileSync(promoBeatStamp, 'utf8').trim() !== promoBeatSum) {
  const { renderPromoBeat } = await import('./render-beat.mjs')
  renderPromoBeat()
  writeFileSync(promoBeatStamp, `${promoBeatSum}\n`)
  console.log('public/audio/promo-beat.wav')
}
