// Gets the video ready to preview or render, without touching design/ or
// plugin/: it copies the design system's stylesheet into src/generated as a
// string, minus its Google Fonts import (the video loads the repository's own
// font files instead), and renders the soundtrack when its score changed.
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const video = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const root = resolve(video, '..')

const css = readFileSync(join(root, 'design/components/bundle.css'), 'utf8').replace(/@import url\([^)]*\);\s*/g, '')
const generated = join(video, 'src/generated')
mkdirSync(generated, { recursive: true })
const out = join(generated, 'design-css.ts')
const body = `// Generated by scripts/prepare.mjs from design/components/bundle.css. Do not edit.\nexport default ${JSON.stringify(css)}\n`
if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
  writeFileSync(out, body)
  console.log('src/generated/design-css.ts')
}

// The icon's layers, as markup to draw inline: as images their outer rings
// and towers would be cut at the canvas's edge, and they stay sharp at any
// size. layers.json says how they stack.
const iconDir = join(root, 'assets/icon-layers')
const layers = JSON.parse(readFileSync(join(iconDir, 'layers.json'), 'utf8'))
const markup = {}
for (const layer of [...layers.layers, layers.mask]) {
  markup[layer.name] = readFileSync(join(iconDir, layer.svg), 'utf8')
    .replace(/<\?xml[^>]*>\s*/, '')
    .replace(/<title>[^<]*<\/title>\s*/, '')
}
const iconOut = join(generated, 'icon-layers.ts')
const iconBody = `// Generated by scripts/prepare.mjs from assets/icon-layers. Do not edit.\nexport const LAYERS = ${JSON.stringify(layers, null, 2)} as const\n\nexport const MARKUP: Record<string, string> = ${JSON.stringify(markup, null, 2)}\n`
if (!existsSync(iconOut) || readFileSync(iconOut, 'utf8') !== iconBody) {
  writeFileSync(iconOut, iconBody)
  console.log('src/generated/icon-layers.ts')
}

// The soundtrack and its sound effects: rendered from their score only when
// the score, its renderer or the running order changed
const score = join(video, 'scripts/music/score.js')
if (existsSync(score)) {
  const hash = createHash('sha256')
    .update(readFileSync(score))
    .update(readFileSync(join(video, 'scripts/render-audio.mjs')))
    .update(readFileSync(join(video, 'src/timeline.ts')))
    .digest('hex')
  const stamp = join(video, 'public/audio/SOURCE')
  const stale = !existsSync(stamp) || readFileSync(stamp, 'utf8').trim() !== hash
  if (stale) {
    const { renderAudio } = await import('./render-audio.mjs')
    await renderAudio()
    mkdirSync(dirname(stamp), { recursive: true })
    writeFileSync(stamp, `${hash}\n`)
  }
}
