// Builds what an install of pipcast gets, in plugin/: the mod bundled into one
// ES module, hooks/register.js, beside its manifest, its state contract, its
// icon and the license. The steps before this one build the station, its page
// and its jingles into plugin/station. Last, it checks that plugin/ holds
// exactly what ships, the files in SHIPS, and stops when it holds anything more
// or anything less.

import { execFileSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'plugin')

// Everything an install gets, as paths in plugin/. A path that ends in / is a
// folder one build step makes whole.
const SHIPS = [
  '.claude-plugin/plugin.json',
  'LICENSE',
  'assets/icon.png',
  'hooks/hooks.json',
  'hooks/register.js',
  'types/index.d.ts',
  'station/pipcast-station',
  'station/sounds/breaking.m4a',
  'station/sounds/breaking-out.m4a',
  'station/sounds/hour.m4a',
  'station/sounds/hour-out.m4a',
  'station/web/',
]

// The engine loads a hooks module as an ES module that imports 'claude-code',
// with JSX compiled against its globals h and Fragment. claude plugin validate
// reads the module's source, so the bundle is never minified: register stays a
// function declared at the top of the file, and every $.noun.method(...) call
// and on('event', ...) keeps its spelling. Paths are relative to the
// repository's root and no tsconfig.json is read, so the bundle comes out the
// same on every machine.
await build({
  absWorkingDir: root,
  entryPoints: ['packages/mod/src/register.tsx'],
  outfile: 'plugin/hooks/register.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: ['claude-code'],
  jsx: 'transform',
  jsxFactory: 'h',
  jsxFragment: 'Fragment',
  charset: 'utf8',
  tsconfigRaw: {},
  banner: { js: '// Built by scripts/build.sh from packages/mod. Do not edit this file: change the sources there and build again.' },
  logLevel: 'warning',
})

writeFileSync(join(out, 'hooks/hooks.json'), '{ "modules": ["./register.js"] }\n')

for (const [from, to] of [
  ['packages/mod/plugin.json', '.claude-plugin/plugin.json'],
  ['packages/mod/types/index.d.ts', 'types/index.d.ts'],
  ['assets/icon-512.png', 'assets/icon.png'],
  ['LICENSE', 'LICENSE'],
]) {
  mkdirSync(dirname(join(out, to)), { recursive: true })
  copyFileSync(join(root, from), join(out, to))
}

// What plugin/ holds: the files on disk that git tracks or would add, less what
// .gitignore keeps out
const held = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', 'plugin'], { cwd: root, encoding: 'utf8' })
  .split('\0')
  .filter((path) => path !== '' && existsSync(join(root, path)))
  .map((path) => path.slice('plugin/'.length))

const covers = (entry, path) => (entry.endsWith('/') ? path.startsWith(entry) : path === entry)
const extra = held.filter((path) => !SHIPS.some((entry) => covers(entry, path)))
const missing = SHIPS.filter((entry) => !held.some((path) => covers(entry, path)))

for (const path of extra) {
  console.error(`Not part of what ships: plugin/${path}`)
}
for (const entry of missing) {
  console.error(`Missing from what ships: plugin/${entry}`)
}
if (extra.length > 0 || missing.length > 0) {
  console.error('plugin/ is what an install copies, and only scripts/build.sh writes it. Keep sources, tests and tools out of it; a new file the plugin needs goes in SHIPS in scripts/build-plugin.mjs, and in the step that builds it.')
  process.exit(1)
}

console.log(`plugin/: ${held.length} files, each one part of what ships`)
