// Writes plugin/src/core/art.generated.ts: the outlines of the band's lettering
// (KLWD, TUNE IN, TUNE OUT) from the station's italic Anybody. A picture the
// desktop draws loads no fonts, so the letters travel as path data.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'
import subsetFont from 'subset-font'

const root = fileURLToPath(new URL('..', import.meta.url))
const fontFile = `${root}assets/fonts/anybody-italic.ttf`
const outFile = `${root}plugin/src/core/art.generated.ts`

const WORDS = [
  { name: 'KLWD', text: 'KLWD', axes: { wght: 900, wdth: 120 }, size: 13, spacing: 0.01 },
  { name: 'TUNE_IN', text: 'TUNE IN', axes: { wght: 900, wdth: 108 }, size: 12, spacing: 0.02 },
  { name: 'TUNE_OUT', text: 'TUNE OUT', axes: { wght: 900, wdth: 108 }, size: 12, spacing: 0.02 },
]

function round(n) {
  const r = Math.round(n * 100) / 100
  return Object.is(r, -0) ? 0 : r
}

async function outline(source, word) {
  const instance = await subsetFont(source, word.text, { targetFormat: 'truetype', variationAxes: word.axes })
  const font = opentype.parse(instance.buffer.slice(instance.byteOffset, instance.byteOffset + instance.byteLength))
  const options = { kerning: true, letterSpacing: word.spacing }
  // The advance, with the spacing after every letter, the last one included
  const width = font.forEachGlyph(word.text, 0, 0, word.size, options, () => {})
  const path = font.getPath(word.text, 0, 0, word.size, options)
  const box = path.getBoundingBox()
  return { d: path.toPathData(2), width: round(width), top: round(box.y1), bottom: round(box.y2) }
}

const source = await readFile(fontFile)
let text = '// Generated by scripts/build-band-art.mjs from assets/fonts/anybody-italic.ttf. Do not edit.\n'
text += 'export interface Word { d: string; width: number; top: number; bottom: number }\n'
for (const word of WORDS) {
  const { d, width, top, bottom } = await outline(source, word)
  text += `export const ${word.name}: Word = { d: '${d}', width: ${width}, top: ${top}, bottom: ${bottom} }\n`
}

await writeFile(outFile, text)
console.log(`wrote ${outFile.slice(root.length)}`)
